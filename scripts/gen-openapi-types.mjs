// Generates src/shared/openapi.generated.ts from the OpenCode OpenAPI snapshot.
// Usage: node scripts/gen-openapi-types.mjs [--url http://127.0.0.1:PORT/openapi.json]
// The generated types are the *raw* shapes the adapter normalises; they are never sent to the webview.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const urlIndex = process.argv.indexOf("--url");
const source = urlIndex >= 0 ? process.argv[urlIndex + 1] : path.join(root, "docs", "openapi-2.2.7.json");
const target = path.join(root, "src", "shared", "openapi.generated.ts");

if (!source) throw new Error("Missing --url value");

const spec = await (async () => {
  if (/^https?:\/\//.test(source)) {
    const res = await fetch(source);
    if (!res.ok) throw new Error(`Cannot fetch ${source}: HTTP ${res.status}`);
    return res.json();
  }
  return JSON.parse(await readFile(source, "utf8"));
})();

const SCHEMAS = [
  "Session.Info",
  "Session.Message.Info",
  "Session.Message.User",
  "Session.Message.Assistant",
  "Session.Message.Idle",
  "Model.Info",
  "Agent.Info",
  "Skill.Info",
  "Permission.Request",
  "Form.Info",
  "FileDiff.Info",
  "SessionsResponse",
  "SessionMessagesResponse",
];

const version = /openapi-(\d+\.\d+\.\d+)\.json/.exec(source)?.[1] ?? spec.info?.version ?? "unknown";

const identifier = (name) => `Api${name.replace(/[^A-Za-z0-9_$]/g, "_")}`;
const safeKey = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key));

function typeOf(schema) {
  if (!schema || typeof schema !== "object") return "unknown";
  if (typeof schema.$ref === "string") return identifier(schema.$ref.split("/").pop());
  if (Array.isArray(schema.enum)) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  const variants = schema.anyOf ?? schema.oneOf;
  if (Array.isArray(variants)) return variants.map(typeOf).join(" | ");
  if (Array.isArray(schema.allOf)) return schema.allOf.map(typeOf).join(" & ");
  switch (schema.type) {
    case "object": {
      const properties = schema.properties ?? {};
      const required = new Set(schema.required ?? []);
      const lines = Object.entries(properties).map(([key, value]) => `  ${safeKey(key)}${required.has(key) ? "" : "?"}: ${typeOf(value)};`);
      return lines.length ? `{\n${lines.join("\n")}\n}` : "{ [key: string]: unknown }";
    }
    case "array":
      return `Array<${typeOf(schema.items)}>`;
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    default:
      return "unknown";
  }
}

const schemas = spec.components?.schemas ?? {};
const missing = SCHEMAS.filter((name) => !schemas[name]);
if (missing.length) throw new Error(`OpenAPI snapshot is missing schemas: ${missing.join(", ")}`);

// Emit the transitive closure of the roots: a generated alias must never reference a name we
// did not emit, otherwise `tsc` fails on an upgrade that changes one nested shape.
const needed = new Set(SCHEMAS);
function collect(schema) {
  if (!schema || typeof schema !== "object") return;
  if (typeof schema.$ref === "string") {
    const name = schema.$ref.split("/").pop();
    if (name && schemas[name] && !needed.has(name)) {
      needed.add(name);
      collect(schemas[name]);
    }
    return;
  }
  for (const key of ["items", "additionalProperties"]) collect(schema[key]);
  for (const key of ["anyOf", "oneOf", "allOf"]) for (const item of schema[key] ?? []) collect(item);
  for (const item of Object.values(schema.properties ?? {})) collect(item);
}
for (const name of SCHEMAS) collect(schemas[name]);

const names = [...needed].sort();
const body = names.map((name) => `export type ${identifier(name)} = ${typeOf(schemas[name])};`).join("\n\n");
const output = `// Generated by scripts/gen-openapi-types.mjs from the OpenCode ${version} OpenAPI schema.\n// Do not edit by hand: run \`npm run gen:types\` after updating the snapshot.\n// These are raw wire shapes; src/shared/adapter.ts converts them to the canonical types.\n\nexport const OPENAPI_SNAPSHOT_VERSION = ${JSON.stringify(version)};\n\n${body}\n`;

await writeFile(target, output, "utf8");
console.log(`Wrote ${path.relative(root, target)} (${names.length} schemas, snapshot ${version})`);
